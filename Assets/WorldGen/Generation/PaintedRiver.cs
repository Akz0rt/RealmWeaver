using System.Collections.Generic;
using System.Numerics;

namespace WorldGen.Generation
{
    /// <summary>
    /// Река, нарисованная кистью (генератор рек тут ни при чём — см. RiverTracer, он выключен).
    /// Хранится как ОПОРНЫЕ точки в мировых координатах Site-пространства: центры клеток, через
    /// которые ДМ провёл курсором, плюс подрезанные концы у кромки воды (RiverPaintOps.TrimToShore).
    /// Сглаженная кривая, которую видно на карте, — производная (RiverPaintOps.Smooth), поэтому в
    /// файле лежит десяток точек, а не сотня, и вид реки можно улучшить позже без правки данных.
    ///
    /// Точки НЕ привязаны к клеткам: правка рельефа и климата русло не двигает. Новая генерация
    /// мира — другое дело: там исчезает сам материк, и нарисованные реки стираются вместе с ним.
    /// </summary>
    public class PaintedRiver
    {
        public int Id;

        /// <summary>Опорные точки русла от истока к устью. Меньше двух точек — реки нет.</summary>
        public List<Vector2> Points = new List<Vector2>();

        /// <summary>Ширина русла в мировых единицах карты (то же пространство, что Site).</summary>
        public float Width = 6f;

        /// <summary>Река встретилась ТОЛЬКО с озером (ни разу с морем) — тогда её красят озёрным
        /// мелководьем, иначе морским. Цвет не хранится: палитра карты переключается на лету, и
        /// запечённый цвет отстал бы от темы (см. WorldMapRenderer.PaintedRiverColor).</summary>
        public bool MouthIsLake;
    }
}
