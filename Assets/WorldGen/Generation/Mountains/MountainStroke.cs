using System.Collections.Generic;
using System.Numerics;

namespace WorldGen.Generation.Mountains
{
    /// <summary>
    /// Одна протяжка кисти гор: ломаная точек в Site-координатах карты и радиус кисти.
    ///
    /// Мазок — ЕДИНСТВЕННОЕ, что попадает в файл проекта. Всё остальное — пятна, маска, поле
    /// расстояний, оси, звенья, доли, сами горы — производное и считается заново. Так же устроены
    /// нарисованные реки (в файле опорные точки, кривая производная) и забор города (не хранится
    /// вовсе), и выигрыш тут не в размере файла: отмена мазка, слившего два массива, ОБЯЗАНА разлить
    /// их обратно, а с производной геометрией это просто «посчитай по оставшимся мазкам» — откатывать
    /// нечего.
    ///
    /// Стирающий мазок хранится наравне с рисующим и вычитается из маски. Поэтому ластик умеет
    /// отгрызть край массива и разрезать его надвое, а отмена стирания возвращает всё как было.
    /// </summary>
    public sealed class MountainStroke
    {
        /// <summary>Порядковый номер. Растёт со временем и НИКОГДА не переиспользуется: по самому
        /// старому мазку пятна берётся зерно разброса (см. MountainBlob.Seed), и от этого зависит,
        /// прыгнет ли уже нарисованный хребет, когда ДМ дорисует к нему отросток.</summary>
        public int Id;

        /// <summary>Точки протяжки, от начала к концу. Одна точка — это тычок кистью, он тоже мазок.</summary>
        public List<Vector2> Points = new List<Vector2>();

        /// <summary>Радиус кисти в мировых единицах карты.</summary>
        public float Radius = 30f;

        /// <summary>Стирающий мазок: вычитается из маски вместо того, чтобы её наращивать.</summary>
        public bool Erase;
    }
}
