using System;

namespace WorldGen.Generation.Mountains
{
    /// <summary>
    /// Раскраска по ярусам: внешнему слою один цвет, среднему другой, внутреннему третий (решение
    /// ДМ 2026-08-14 — «чтобы чётко читалась форма каждой горной массы»).
    ///
    /// Здесь только ДОЛЯ вдоль шкалы «светлый → тёмный», без единого цвета: сами концы шкалы берутся
    /// из палитры карты и живут в рендере. Правило вынесено в чистый слой ровно затем, чтобы его
    /// проверял стенд, — цвета Unity ему не видны.
    ///
    /// Ярус берётся АБСОЛЮТНЫЙ — тот, что §11 задаёт формулой ярус = min(n−1, ⌊D/2R⌋), а не
    /// нормированный на самую глубокую точку массы. Разница видна на узком мазке: у него слоёв всего
    /// один-два, и он честно выходит одноцветным вместо того, чтобы притворяться полноценным
    /// хребтом с ядром. Нормировка есть у ВЫСОТЫ (MountainGeometry.AssignTiers), и там она нужна по
    /// обратной причине — иначе узкий мазок вышел бы поголовно приземистым; путать эти два правила
    /// нельзя, они решают разные задачи.
    /// </summary>
    public static class MountainTierRamp
    {
        /// <summary>
        /// Доля вдоль шкалы: 0 — светлый конец, 1 — тёмный.
        ///
        /// tierCount — сколько ярусов РАЗЛИЧАЕМ по настройке, а не сколько их набралось у этой
        /// массы. Иначе гряда из двух слоёв красилась бы теми же тремя красками, что и большой
        /// массив, и «внутренний цвет» перестал бы значить «сердцевина».
        ///
        /// contrast — насколько ярусы расходятся: 1 — во всю шкалу (ядро тёмное), 0 — все ярусы
        /// одного среднего цвета, −1 — наоборот, ядро светлое. Середина шкалы неподвижна: при нуле
        /// масса не должна ни посветлеть, ни потемнеть целиком, у неё лишь пропадают полосы.
        /// </summary>
        public static float Mix(int tier, int tierCount, float contrast)
        {
            int count = Math.Max(1, tierCount);
            int last = Math.Max(1, count - 1);
            int t = Math.Min(Math.Max(tier, 0), count - 1);

            float step = (float)t / last;
            float c = Math.Min(1f, Math.Max(-1f, contrast));
            return 0.5f + (step - 0.5f) * c;
        }
    }
}
