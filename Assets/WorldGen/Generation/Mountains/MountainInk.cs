using System;
using System.Numerics;

namespace WorldGen.Generation.Mountains
{
    /// <summary>
    /// Манера «тушь» (§13): ЧЕМ и НАСКОЛЬКО ЧЕРНО рисуется гора. Все числа здесь — постоянные,
    /// подобранные по образцу ДМ; ползунков на них больше нет ни одного.
    ///
    /// ПОЧЕМУ ПОЛЗУНКИ УБРАНЫ (решение ДМ 15 августа 2026). Пока каждое число было ползунком, вид
    /// гор зависел от того, какие значения лежали в сцене, а не от того, что выбрано в превью, — и
    /// дважды подряд картинка расходилась именно так. Число, которое можно случайно сдвинуть, рано
    /// или поздно оказывается сдвинутым. Здесь его сдвинуть нечем.
    ///
    /// ТРИ ПРАВИЛА МАНЕРЫ, и больше в ней ничего нет:
    ///   1. Объём держит ЛИНИЯ — один непрерывный контур на гору (MountainOutline), жирный у
    ///      вершины, сходящий на нет книзу.
    ///   2. ПОЛНАЯ ТЕНЬ — и только она — засеяна точками. Не «чем темнее, тем чаще», а порог:
    ///      либо сторона в тени и на ней зерно, либо она чистая.
    ///   3. Освещённый склон — ЧИСТАЯ БУМАГА. Ни растушёвки, ни промоин, ни полутонов.
    ///
    /// Живёт в ЧИСТОМ слое нарочно: всё, что лежит в Rendering, не проверяет никто, кроме
    /// компилятора. «Сколько меток класть» и «какая сторона в тени» глазом не проверить — они врут
    /// тихо и на всей карте разом.
    /// </summary>
    public static class MountainInk
    {
        // ── линия ───────────────────────────────────────────────────────────────────────────────

        /// <summary>
        /// Жирность линии у вершины, в долях радиуса горы.
        ///
        /// Прежде здесь стояло 0.55·R, и это была ошибка КАЛИБРОВКИ ПО СУММЕ: число подбирали так,
        /// чтобы доля тёмных пикселей совпала со снимком ДМ. Доля совпала, манера разошлась — в
        /// браузере тонкая линия обводила каждое из восемнадцати колец и складывалась в контур, а в
        /// приложении та же «сумма туши» вышла одним жирным клином. Мерить надо РАСПРЕДЕЛЕНИЕ
        /// толщин, а не их сумму: у превью медиана тёмного пробега 3 px при p90 = 7, у прежнего
        /// приложения — 2 при p90 = 12 и max 72.
        /// </summary>
        public const float PenWidth = 0.36f;

        /// <summary>Сход линии на нет книзу: толщина = жирность·(1 − r)^сход, где r — ярус, на
        /// котором в этой точке достигнут верх. У краёв контура r = 1 и толщина ровно ноль, поэтому
        /// низ не обводится САМ СОБОЙ, без единой проверки «а здесь не рисовать».</summary>
        public const float PenTaper = 1.0f;

        /// <summary>
        /// Толщина, ниже которой линия обрывается, в долях радиуса.
        ///
        /// Нужна из-за экрана, а не из-за математики. Полоса тоньше пикселя не рисует линию — она
        /// подмешивает серого, и контур читается полупрозрачным. Именно это ДМ и увидел: хвост
        /// линии уходил в ноль, и последняя его треть была подпиксельной. Обрыв честнее растворения.
        /// </summary>
        public const float PenFloor = 0.02f;

        /// <summary>Насколько слой массы меняет густоту туши: внутренние слои жирнее линией и
        /// плотнее крошкой. Градация «внешний / средний / внутренний» переехала сюда из цвета — на
        /// образце ДМ цветов нет вовсе, а требование различать слои осталось.</summary>
        public const float TierInk = 0.5f;

        /// <summary>Направление градации по слоям: сердцевина гуще края.</summary>
        public const float TierContrast = 1f;

        /// <summary>Откуда светит, в градусах. Одно направление на всю карту: разное освещение у
        /// соседних гор рассыпает картинку.</summary>
        public const float LightAngle = 160f;

        /// <summary>Единичный вектор света.</summary>
        public static Vector2 Light
        {
            get
            {
                double a = LightAngle * Math.PI / 180.0;
                return new Vector2((float)Math.Cos(a), (float)Math.Sin(a));
            }
        }

        // ── крошка ──────────────────────────────────────────────────────────────────────────────

        /// <summary>
        /// Сколько меток крошки приходится на одну R² площади подошвы.
        ///
        /// Число браузерное (там плотность считалась как площадь_подошвы/9 при радиусе 10, то есть
        /// 100/9 на R²). Оно уже стояло здесь однажды, потом было поднято до 81 — вместе с тем, как
        /// метку уменьшили втрое, «чтобы тон крошки остался прежним». ТОН ОСТАЛСЯ, ЗЕРНО ПРОПАЛО:
        /// метка меньше пикселя не рисует точку, она красит пиксель наполовину. Двадцать шесть
        /// процентов всех тёмных пробегов на снимке ДМ были ровно в один пиксель — это и есть
        /// «грязно». Возвращено к браузерному вместе с размером метки.
        ///
        /// Оговорка, которую надо знать: при СИЛЬНОМ приближении метка снова читается квадратиком.
        /// Выбор сознательный — вид калибруется на том масштабе, на котором ДМ смотрит карту.
        /// </summary>
        public const float GritPerArea = 11.1f;

        /// <summary>Густота крошки. Множитель к GritPerArea; выбор ДМ в браузере.</summary>
        public const float Grit = 0.80f;

        /// <summary>
        /// Насколько крошка жмётся к гребню. Больше — плотнее у вершины, реже у подошвы.
        ///
        /// Поднято против браузерных 0.4: в браузере тело горы было залито краской, и крошка на
        /// юбке читалась частью горы. Здесь тело ПРОЗРАЧНО (окно в карту), и та же крошка на юбке —
        /// просто зерно посреди карты, ни к чему не прикреплённое. ДМ увидел это как грязь.
        /// </summary>
        public const float GritFall = 0.4f;

        /// <summary>
        /// Порог тени: метки кладутся ТОЛЬКО там, где склон отвёрнут от света не меньше чем на
        /// столько.
        ///
        /// Прежде порога не было вовсе — метка ставилась с вероятностью, растущей от освещённости,
        /// и одиночные точки сеялись по всей горе, включая освещённую сторону. Образец ДМ
        /// устроен иначе: «освещённый склон — чистая бумага, теневой — зернистая крошка».
        /// Полутонов между ними нет, значит и в правиле их быть не должно.
        /// </summary>
        public const float ShadeThreshold = 0.45f;

        /// <summary>Потолок меток на одну гору — предохранитель от разгона, а не рабочее
        /// ограничение. Молчать он не должен: MarkCount выдаёт наружу признак «упёрлись».</summary>
        public const int GritCap = 900;

        /// <summary>
        /// Сколько меток крошки положить на гору.
        ///
        /// Считается от ПЛОЩАДИ ПОДОШВЫ, и это главное. В браузерном прототипе плотность считалась
        /// по ярусам, и она тайно цеплялась за ползунок «ярусов»: подняв его ради гладкого силуэта,
        /// ДМ разом затемнил бы всю картину и не понял, отчего. Площадь мерится в R², поэтому
        /// мелкие и крупные горы выглядят одинаково — как и всё остальное в этом алгоритме.
        /// </summary>
        public static int MarkCount(float footArea, float radius, float density, out bool capped)
        {
            capped = false;
            if (footArea <= 0f) return 0;

            float r2 = Math.Max(1e-4f, radius * radius);
            int count = (int)(Grit * density * footArea / r2 * GritPerArea + 0.5f);
            if (count <= 0) return 0;
            if (count > GritCap) { capped = true; return GritCap; }
            return count;
        }

        /// <summary>
        /// Размер одной метки крошки, в мировых единицах. u — равномерное число от 0 до 1.
        ///
        /// Доля радиуса, а не пиксели: мелкие и крупные горы обязаны выглядеть одинаково. Числа
        /// браузерные — те, при которых ДМ смотрел и одобрял. Промежуточная редакция уменьшила их
        /// втрое, чтобы вблизи не читалось кубиками, и тем убила зерно на рабочем масштабе; см.
        /// GritPerArea.
        /// </summary>
        public static float MarkSize(float radius, float u)
        {
            if (u < 0f) u = 0f; else if (u > 1f) u = 1f;
            return radius * (0.07f + u * 0.13f);
        }

        /// <summary>
        /// На каком r сидит метка крошки. Смещение вверх задаётся показателем «редеет вниз»: при
        /// нуле метки лежат равномерно по склону, чем больше — тем плотнее жмутся к гребню.
        /// u — равномерное число от 0 до 1.
        /// </summary>
        public static float MarkR(float u, float fall)
        {
            float p = 1f / (Math.Max(0f, fall) + 1f);
            float t = (float)Math.Pow(u < 0f ? 0f : (u > 1f ? 1f : u), p);
            return 1f - (1f - MountainProfile.ApexRadius) * t;
        }

        // ── общие правила ───────────────────────────────────────────────────────────────────────

        static float Clamp01(float v) => v < 0f ? 0f : (v > 1f ? 1f : v);

        /// <summary>
        /// Толщина линии в точке контура, в долях жирности. r — ярус, на котором в этой точке
        /// достигнут верх: 1 у краёв, ближе к нулю у вершины.
        ///
        /// При r = 1 выходит РОВНО ноль при любом показателе. Поэтому низ не обводится сам собой и
        /// контур обрывается — то, чего требовал образец ДМ. Ни одной проверки «а здесь не
        /// обводить» в коде нет и быть не должно: правило одно и работает везде.
        /// </summary>
        public static float Taper(float r, float exponent)
        {
            float t = 1f - r;
            if (t <= 0f) return 0f;
            if (t > 1f) t = 1f;
            return (float)Math.Pow(t, Math.Max(0.01f, exponent));
        }

        /// <summary>
        /// МЕРА ГОРЫ, от которой берётся толщина линии: меньшая из полуширины и высоты.
        ///
        /// Не общий радиус R. Горы одного массива разнятся втрое: на внешнем слое они низкие и
        /// широкие, на внутреннем — высокие и узкие. Линия в долях R у всех выходит одна, и на узкой
        /// горе два её склона смыкаются в чёрный столб, а цепь таких гор — в частокол (замер на
        /// фикстуре «Горная страна»: высота 31 при ширине подошвы 19 и линии 5.2).
        ///
        /// Берём МЕНЬШЕЕ из двух, потому что подвести может любое: на высокой и узкой линия упирается
        /// в ширину, на низкой и широкой — в высоту.
        /// </summary>
        public static float PenScale(MountainShape shape)
        {
            float half = 0.5f * Math.Max(0f, shape.SpanX);
            float height = Math.Max(0f, shape.Height);
            return Math.Min(half, height);
        }

        /// <summary>Полутолщина линии в точке контура, в мировых единицах. Ноль значит «здесь линию
        /// не вести»: либо мы у самого низа, либо полоса вышла тоньше пикселя (см. PenFloor).</summary>
        public static float HalfWidth(float r, MountainShape shape, float radius, float density)
        {
            float w = PenWidth * PenScale(shape) * Taper(r, PenTaper) * density;
            return w < PenFloor * radius ? 0f : 0.5f * w;
        }

        /// <summary>
        /// Ложится ли метка туши на землю: спрашиваем про место ПОДОШВЫ, а не про нарисованное.
        ///
        /// Тело горы — окно в карту и не красит ничего, поэтому от юбки, заехавшей в озеро,
        /// остаётся одна крошка: несколько зёрен посреди воды, ни к чему не прикреплённых. ДМ увидел
        /// это как грязь и как «линии заходят на водоёмы».
        ///
        /// Мерить надо именно подошву (см. MountainTriangulation.Foot): у прибрежной горы вершина
        /// НАРИСОВАНА над водой, что позади неё, и это правильно — гора возвышается. Отсекать по
        /// нарисованному месту значило бы срезать ей макушку.
        ///
        /// land = null — ограничения нет вовсе: так работает стенд, где никакой воды не существует.
        /// </summary>
        public static bool Grounded(Func<Vector2, bool> land, MountainShape shape, int index, float r)
            => land == null || land(MountainTriangulation.Foot(shape, index, r));

        /// <summary>Ложится ли метка туши на землю — по произвольной точке подошвы. Нужна контуру:
        /// у него нет «номера луча», он идёт по x.</summary>
        public static bool GroundedAt(Func<Vector2, bool> land, Vector2 footPoint)
            => land == null || land(footPoint);

        /// <summary>Насколько точка в тени: 1 — прямо от света, 0 и ниже — освещена. normal —
        /// наружу глядящая нормаль подошвы, light — единичный вектор направления света.</summary>
        public static float Shade(Vector2 normal, Vector2 light)
            => -(normal.X * light.X + normal.Y * light.Y);

        /// <summary>Полная ли это тень. Порог, а не плавность: см. ShadeThreshold.</summary>
        public static bool InShadow(Vector2 normal, Vector2 light)
            => Shade(normal, light) >= ShadeThreshold;

        /// <summary>Густота туши для слоя массы: множит и толщину линии, и плотность крошки.</summary>
        public static float Density(int tier, int tierCount)
        {
            float band = MountainTierRamp.Mix(tier, tierCount, TierContrast);
            float k = 1f + TierInk * (band - 0.5f) * 2f;
            return k < 0.15f ? 0.15f : k;
        }
    }
}
