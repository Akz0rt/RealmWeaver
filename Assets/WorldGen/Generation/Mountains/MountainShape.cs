using System.Numerics;

namespace WorldGen.Generation.Mountains
{
    /// <summary>
    /// Одна гора — то, что геометрический слой отдаёт наружу рендеру (§10 спеки). Намеренно не
    /// «готовый меш» и не «список треугольников»: манера рисования меняется, а математика — нет.
    ///
    /// Гора устроена как стопка ярусов: тот же силуэт подошвы, взятый с долей r и поднятый на
    /// H·lift(r). Но НИ ОДИН ярус здесь не хранится, и это главное решение переноса.
    ///
    /// Почему. Ярусы нужны были затем, чтобы огибающая стопки выходила гладкой. В браузере их и
    /// рисовали все подряд, а лишнее закрывали заливкой — там это ничего не стоит. В меше это стоило
    /// бы восемнадцати колец по сотне вершин на каждую из пятисот гор. Между тем внешнюю границу
    /// стопки можно посчитать ТОЧНО и сразу.
    ///
    /// Кольцо радиуса r — это подошва, сжатая к середине звена и поднятая. Значит вдоль луча из
    /// середины под углом θ оно достаёт до
    ///
    ///     f(r) = r·d(θ) + H·lift(r)·n_y(θ)
    ///
    /// где d — полурадиус подошвы в этом направлении, а n_y — вертикальная доля единичного вектора
    /// луча. Наружная граница объединения по этому лучу — просто max по r. Считается перебором
    /// двух десятков значений r и даёт ЗАМКНУТУЮ ЛОМАНУЮ ровно из тех же точек, что и подошва.
    ///
    /// Отсюда всё остальное падает даром:
    /// • тело — веер из середины звена на эту ломаную (по треугольнику на точку);
    /// • линия туши — лента вдоль неё же, а толщина в каждой точке берётся из того самого r, на
    ///   котором достигнут максимум: у ближнего края максимум сидит на r = 1, толщина там нулевая,
    ///   и подошва не обводится сама собой;
    /// • крошка и промоины считаются прямо по меридиану P(r) и колец тоже не требуют.
    ///
    /// Вышло примерно в двадцать раз меньше треугольников, чем при честной стопке, и картинка при
    /// этом не приблизительная, а более точная: граница посчитана, а не получена закрашиванием.
    /// </summary>
    public sealed class MountainShape
    {
        /// <summary>Подошва — ярус 0: доля-гармошка, растянутая вдоль оси и сплющенная по вертикали.
        /// Замкнутая ломаная. Из неё же берутся направления лучей.</summary>
        public Vector2[] Base;

        /// <summary>Наружу глядящая нормаль подошвы в каждой точке. Считается при построении и
        /// хранится: по ней решается, какая сторона горы в тени, а пересчитывать её в рендере значит
        /// повторять работу для каждой из сотен гор на каждую перерисовку.</summary>
        public Vector2[] Normal;

        /// <summary>Середина звена: центр, к которому стягиваются ярусы и от которого идут лучи.</summary>
        public Vector2 Centre;

        /// <summary>H — высота горы над серединой звена.</summary>
        public float Height;

        /// <summary>Острота (§10), нужна рендеру, чтобы считать меридиан для крошки и промоин.</summary>
        public float Sharp;

        /// <summary>Радиусы ярусов, от 1 (подошва) до ApexRadius (вершина). Сколько их — решает
        /// кривизна самой кривой подъёма: у конуса меридиан прямой и хватает двух, у купола нужен
        /// десяток. Это ЗАЛИВКА тела; линия туши считается иначе (см. Silhouette).</summary>
        public float[] LevelR;

        /// <summary>Точка внешней границы на каждом луче — туда ляжет линия туши. НЕ замкнутая
        /// ломаная: у конуса максимум сидит либо на подошве, либо на вершине, и у соседних лучей
        /// он скачет между ними. Соединять эти точки подряд нельзя — выйдет клубок (проверено
        /// стендом: 68 самопересечений из 115). Поэтому линия рисуется не лентой вдоль них, а
        /// короткими штрихами В каждой точке, по касательной к своему ярусу: штрихи перекрываются
        /// и читаются сплошной линией, а порядка обхода им не нужно вовсе.</summary>
        public Vector2[] Silhouette;

        /// <summary>На каком r достигнута граница в каждой точке. 1 — граница на самой подошве
        /// (ближний край), ближе к нулю — на вершине. Задаёт толщину линии.</summary>
        public float[] SilhouetteR;

        /// <summary>Y ближайшей к зрителю точки подошвы. Ключ сортировки маляра: МЕНЬШЕ — ближе,
        /// значит рисуется позже.</summary>
        public float Depth;

        /// <summary>Слой массы (§11): 0 — гряда по краю, дальше внутрь. Задаёт высоту и густоту
        /// туши. В версии 0.9 документа назывался «ярусом» — теперь так зовут уровень внутри горы.</summary>
        public int Tier;

        /// <summary>Зерно всего случайного в рисунке этой горы, взятое от её МЕСТА на карте. Иначе
        /// крошка пересеивается на каждую перерисовку и картинка дрожит.</summary>
        public uint Seed;

        /// <summary>Площадь габарита подошвы. По ней считается, сколько класть крошки: плотность
        /// должна быть на единицу площади, а не на гору и не на ярус.</summary>
        public float FootArea;
    }
}
