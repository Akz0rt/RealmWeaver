using System.Collections.Generic;
using System.Numerics;

namespace WorldGen.Generation.Mountains
{
    /// <summary>
    /// Одна гора — то, что геометрический слой отдаёт наружу рендеру (§10 спеки). Намеренно не
    /// «готовый меш» и не «список треугольников»: манера рисования будет меняться (сейчас тон по
    /// глубине, дальше боковой свет, штриховка, разные формы вершин), а математика — нет. Всё, что
    /// нужно любой манере, лежит здесь.
    ///
    /// Обе цепи идут СЛЕВА НАПРАВО и начинаются с одной точки, кончаются другой — левым и правым
    /// краем подошвы. Так их можно сшить в треугольники простым проходом по X, без общего алгоритма
    /// триангуляции: фигура монотонна по горизонтали по построению.
    /// </summary>
    public sealed class MountainShape
    {
        /// <summary>Видимый гребень: левый склон, вершина, правый склон. Это единственное, что
        /// обводится линией — дуга подошвы не обводится, иначе она прочерчивает соседа поперёк и
        /// массив рассыпается в чешую (§10).</summary>
        public List<Vector2> Crest = new List<Vector2>();

        /// <summary>Ближняя (нижняя по экрану) дуга подошвы, слева направо. Вместе с гребнем
        /// замыкает силуэт горы.</summary>
        public List<Vector2> Front = new List<Vector2>();

        /// <summary>Вершина.</summary>
        public Vector2 Apex;

        /// <summary>Y ближайшей к зрителю точки подошвы. Ключ сортировки маляра: МЕНЬШЕ — ближе,
        /// значит рисуется позже. Он же даёт тон (воздушная перспектива).</summary>
        public float Depth;

        /// <summary>Ярус звена (§11).</summary>
        public int Tier;
    }
}
