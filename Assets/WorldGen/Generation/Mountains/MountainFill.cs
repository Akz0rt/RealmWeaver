using System;

namespace WorldGen.Generation.Mountains
{
    /// <summary>
    /// Заливка тела горы: КАКОГО ТОНА кусок горы под этой точкой (решение ДМ 17 августа 2026).
    ///
    /// Здесь только ДОЛЯ вдоль шкалы «светлый → тёмный», без единого цвета: концы шкалы берутся из
    /// палитры карты (MtnL — светлый горный тон, MtnS — теневой) и живут в рендере. Правило вынесено
    /// в чистый слой ровно затем, чтобы его проверял стенд: цвета Unity ему не видны, а числа видны.
    ///
    /// ДВА «УРОВНЯ» ВЛОЖЕНЫ ДРУГ В ДРУГА, и путать их нельзя — слово занято дважды (§1 документа):
    ///   • СЛОЙ МАССЫ (§11, shape.Tier: внешний / средний / внутренний) выбирает ПОЛОСУ на шкале.
    ///     Он и отвечает за требование ДМ «тона разные для разных уровней гор»: у края массы горы
    ///     светлые, к сердцевине темнеют, и форма массы читается сама.
    ///   • ЯРУС САМОЙ ГОРЫ (§10, кольца тела) гуляет ВНУТРИ этой полосы: подошва у тёмного края
    ///     полосы, вершина у светлого. Это и есть градиент, о котором просил ДМ.
    /// Полоса УЖЕ зазора между слоями (BandWidth &lt; 1) — иначе градиент одной горы дотянулся бы до
    /// тона соседнего слоя, и «внешний / средний / внутренний» перестали бы различаться. Ровно это
    /// вложение ДМ выбрал ещё 14 августа («слой массы берёт полосу на шкале, ярус горы гуляет внутри
    /// неё»), тогда — для густоты туши; здесь оно применено к тону.
    ///
    /// ЗАЛИВКА НЕПРОЗРАЧНА, и это не мелочь. Горы вдоль гряды лежат внахлёст по многу штук; любая
    /// прозрачность складывается на стыках и даёт ту самую грязь, из-за которой непрозрачной сделали
    /// и тушь (см. MountainPaintStyle.DefaultInk). Непрозрачной краске к тому же не нужно ни строчки
    /// в шейдере: тела уже пишут глубину, ближняя гора кладётся поверх дальней, и каждая точка
    /// красится ровно один раз.
    ///
    /// Чем это оплачено: «тело — окно в карту» отменяется. До 17 августа тело клалось прозрачным, и
    /// сквозь гору была видна карта со всем её сглаживанием и зерном. Вернуть это можно (тело пишет
    /// глубину, а тон кладётся вторым проходом с ZTest Equal — тогда каждая точка красится один раз
    /// даже полупрозрачной краской), но это стоит второго прохода по телу.
    /// </summary>
    public static class MountainFill
    {
        /// <summary>
        /// Ширина полосы одного слоя массы, в долях ЗАЗОРА между соседними слоями.
        ///
        /// Меньше единицы обязано быть по построению: при единице полосы соседних слоёв смыкаются, и
        /// самая тёмная гора внешнего слоя выходит того же тона, что самая светлая гора среднего, —
        /// градация по слоям пропадает, хотя ни одно другое число не менялось. Проверка стенда
        /// «слои не налезают друг на друга» стережёт именно это.
        /// </summary>
        public const float BandWidth = 0.6f;

        /// <summary>Направление градации по слоям: сердцевина массы темнее края. То же, что у туши
        /// (MountainInk.TierContrast), но число своё: у тона и у густоты чернил разные поводы
        /// меняться.</summary>
        public const float TierContrast = 1f;

        /// <summary>
        /// Куда идёт градиент внутри одной горы: 1 — вершина светлее подошвы, −1 — наоборот, 0 —
        /// градиента нет вовсе и гора заливается одним тоном своего слоя.
        ///
        /// Единица взята потому, что так гора читается объёмной при взгляде сверху: низ уходит в
        /// тень соседних гор, макушка ловит свет. Ноль оставлен рабочим значением намеренно — это
        /// честный вариант «просто три тона по слоям», и на листе вариантов его видно рядом.
        /// </summary>
        public const float Gradient = 1f;

        /// <summary>
        /// Какую часть шкалы палитры занимает заливка: 1 — от светлого горного тона до теневого во
        /// всю глубину, 0.5 — только верхняя половина пути, 0 — все горы светлым тоном.
        ///
        /// Нужен потому, что концы шкалы выбирала не эта арка: MtnS — почти чёрный (40,46,56), и при
        /// полном размахе сердцевина массы сливается с тушью в тёмное пятно. Размах жмёт всю шкалу
        /// целиком, поэтому НИ ОДНО другое правило от него не меняется: и полосы слоёв, и градиент
        /// внутри горы остаются на своих местах, просто в более тесном тоне.
        ///
        /// ЕДИНИЦА — ВЫБОР ДМ 17 августа, из четырёх вариантов на листе (1.0 / 0.6 / 0.6 без
        /// градиента / 0.35), и выбор осознанно ПРОТИВ моего совета: «у нас дарк-фэнтези стиль».
        /// То, что я счёл слипанием сердцевины с тушью, для этого стиля и нужно. Не «улучшать»
        /// осветлением: лист вариантов ДМ видел, тёмный он взял намеренно.
        /// </summary>
        public const float ToneSpan = 1f;

        /// <summary>
        /// Доля вдоль шкалы: 0 — светлый конец (MtnL), 1 — тёмный (MtnS).
        ///
        /// tierCount — сколько слоёв массы РАЗЛИЧАЕМ по настройке (MountainSettings.Tiers), а не
        /// сколько их набралось у этой массы. Иначе узкая гряда из одного слоя красилась бы так же,
        /// как сердцевина большого массива, и «внутренний тон» перестал бы значить «сердцевина».
        /// Та же оговорка, что у MountainTierRamp, и по той же причине.
        ///
        /// rise — подъём точки внутри САМОЙ горы: 0 на подошве, 1 на вершине (это в точности
        /// LiftSamples.LiftAt яруса). Нормировка на свою гору обязательна: горы одного массива
        /// разнятся высотой втрое, и общая мера сделала бы низкие горы поголовно тёмными.
        /// </summary>
        public static float Tone(int tier, int tierCount, float rise)
        {
            int count = Math.Max(1, tierCount);
            float gap = count > 1 ? 1f / (count - 1) : 1f;
            float half = 0.5f * Clamp01(BandWidth) * gap;

            // Шкала СЖИМАЕТСЯ на полполосы с каждого конца, и полоса ложится целиком внутрь неё.
            // Без сжатия у внешнего слоя (mix = 0) вершина ушла бы за светлый конец, и её пришлось
            // бы обрезать — а обрезка даёт горе плоскую макушку одного тона вместо градиента.
            float mix = MountainTierRamp.Mix(tier, count, TierContrast);
            float band = half + mix * (1f - 2f * half);

            return (band + (0.5f - Clamp01(rise)) * 2f * half * Gradient) * Clamp01(ToneSpan);
        }

        /// <summary>
        /// Смешать две краски по тону, поканально. 0 — светлая целиком, 1 — тёмная целиком.
        ///
        /// Смешивается в том пространстве, в каком краски пришли (у нас sRGB из палитры), а перевод
        /// в линейное делается ПОСЛЕ и один раз на ярус — см. MountainPaintStyle.Fill. Порядок
        /// важен: перевести сперва, а смешать потом — значит получить другую середину шкалы.
        /// </summary>
        public static byte Blend(byte light, byte dark, float tone)
        {
            float t = Clamp01(tone);
            float v = light + (dark - light) * t;
            if (v <= 0f) return 0;
            if (v >= 255f) return 255;
            return (byte)(v + 0.5f);
        }

        static float Clamp01(float v) => v < 0f ? 0f : (v > 1f ? 1f : v);
    }
}
