using System.Collections.Generic;
using System.Numerics;

namespace WorldGen.Generation.Mountains
{
    /// <summary>
    /// Звено оси — участок примерно постоянной длины, из которого вырастает ОДНА гора (§8 спеки
    /// `docs/mountain-brush-algorithm.pdf`). Стык двух соседних звеньев называется позвонком: там
    /// масса перетянута, и из этой перетяжки получается «гармошка» §9.
    ///
    /// Пространство — Site-координаты карты (то же, в котором живут VoronoiCell.Site и нарисованные
    /// реки). ВАЖНО про ось Y: в прототипе холст растёт вниз, а у нас +Y — это «вверх по экрану»
    /// (камера смотрит сверху, Site.y ложится в мировую Z). Поэтому везде, где прототип вычитал
    /// высоту, мы её прибавляем, а «ближняя» дуга подошвы — та, у которой Y МЕНЬШЕ.
    /// </summary>
    public sealed class AxisLink
    {
        /// <summary>Точки звена вдоль оси, от начала к концу.</summary>
        public List<Vector2> Pts = new List<Vector2>();

        /// <summary>Полуширина массы в каждой точке: значение поля расстояний, ограниченное сверху
        /// потолком (§9: R для колец, 1.6R для скелета). Длина совпадает с Pts.</summary>
        public List<float> Ws = new List<float>();

        /// <summary>Середина звена — над ней ставится вершина.</summary>
        public Vector2 Mid;

        /// <summary>Единичная касательная к оси в середине звена.</summary>
        public Vector2 Tan;

        /// <summary>Полуширина в середине звена: из неё считается высота горы (H = h·w).</summary>
        public float MidW;

        /// <summary>Ярус (§11): 0 — гряда по краю мазка, дальше вглубь. Он же будущий уровень
        /// детализации, поэтому выдаётся наружу вместе с геометрией.</summary>
        public int Tier;

        /// <summary>Детерминированный разброс высоты (0.82…1.18), чтобы гряда не выглядела
        /// штампованной.</summary>
        public float HeightJitter = 1f;

        /// <summary>Множитель высоты яруса (§11): край массива ниже, сердцевина выше.</summary>
        public float TierScale = 1f;
    }
}
