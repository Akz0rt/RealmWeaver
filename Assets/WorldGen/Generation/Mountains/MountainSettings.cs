using System;

namespace WorldGen.Generation.Mountains
{
    /// <summary>
    /// Все числа алгоритма в одном месте, в мировых единицах карты. Значения по умолчанию — те, что
    /// подобраны в прототипе `docs/mountain-brush-step1.html` (радиус горы там 44 px, и всё остальное
    /// выражено через него), поэтому здесь они записаны В ДОЛЯХ РАДИУСА, а не в пикселях: тогда
    /// мелкие и крупные горы выглядят одинаково.
    ///
    /// Настройки живут отдельно от геометрии по той же причине, по какой отдельно живёт MountainShape:
    /// в задаче 6 их будет крутить ДМ ползунками, а в задаче 10 подобранное станет новыми дефолтами.
    /// </summary>
    public sealed class MountainSettings
    {
        // Значения по умолчанию — ВЫБОР ДМ от 14 августа 2026, те же, что стоят полями в
        // MountainLayer. Держать их врозь нельзя: 14 августа стенд рисовал талией 0.55 и
        // растяжением 1.4, пока приложение рисовало 0.95 и 1.9, — и картинка со стенда честно не
        // походила на превью. Разошлись ровно те два числа, которые решают, насколько подошвы
        // соседей перекрываются, то есть читается гряда единой массой или рядом отдельных палаток.

        /// <summary>
        /// Сглаживание контура массива, в радиусах горы. Клетки карты стоят через 15 единиц, а гора
        /// — 10, поэтому без сглаживания контур выходит мозаикой.
        ///
        /// Постоянная, а не поле: это число вида, а не вкуса, и ползунка на него больше нет.
        /// </summary>
        public const float MaskSmoothing = 0.5f;

        /// <summary>R — радиус горы. Задаёт и шаг слоёв 2R при отборе колец, и предельную полуширину
        /// массы, и всё остальное ниже.</summary>
        public float Radius = 10f;

        /// <summary>T = LinkFactor·R — целевая длина звена (§8).</summary>
        public float LinkFactor = 1.6f;

        /// <summary>Разброс длин звеньев: вес звена берётся из 1 ± LengthJitter. Шесть процентов —
        /// достаточно, чтобы гряда не выглядела штампованной, и мало, чтобы звенья не разъезжались.</summary>
        public float LengthJitter = 0.06f;

        /// <summary>a — угол взгляда на землю, одним числом. В метрике §8 вертикаль «дороже» в a раз
        /// (позвонки на вертикальных участках ложатся чаще), а подошва горы во столько же раз
        /// сплющена по вертикали. Это одно и то же соглашение о взгляде, поэтому и число одно.</summary>
        public float Anisotropy = 1.6f;

        /// <summary>t — талия на позвонке: доля полной полуширины на стыке звеньев (§9).</summary>
        public float Waist = 0.95f;

        /// <summary>h — множитель высоты: H = h·w, где w — полуширина в середине звена.</summary>
        public float HeightFactor = 2.2f;

        /// <summary>k — растяжение подошвы вдоль оси (§10). Больше — выше перевалы, плотнее массив.</summary>
        public float Stretch = 1.9f;

        /// <summary>
        /// Острота вершины (§10), от 0 до 1: купол → синусоида → конус → шпиль. Заменила показатель
        /// склона. Разница не в записи, а в устройстве: показатель гнул ОДИН силуэт и умел выгнуть
        /// его так, что тот сам себя пересекал; острота смешивает готовые убывающие кривые, и
        /// негодного положения у ползунка нет вовсе.
        /// </summary>
        public float Sharp = 0.66f;

        /// <summary>
        /// Зубчатость гребня (§13): выщербины на линии. Множит ОТСТУП точки подошвы от середины
        /// звена, а не сдвигает саму точку, — поэтому выщербина стягивается вместе с ярусом и
        /// вложенность ярусов сохраняется. Зерно берётся от места на карте (MoundBuilder.SeedAt):
        /// иначе рисунок пересеивается на каждую перерисовку и дрожит.
        /// </summary>
        public float Jag = 0.03f;

        /// <summary>Сколько слоёв массы различаем (§11). Слой 0 — гряда по краю массива.
        /// Постоянная: от неё зависит и высота гор, и густота туши, и ползунка на неё больше нет.</summary>
        public const int Tiers = 3;

        /// <summary>Высота горы нулевого яруса как доля высоты самого глубокого (§11).</summary>
        public float EdgeHeight = 0.55f;

        // Размах тональной шкалы (ToneSpan) снят 2026-08-14 вместе с заливкой по глубине: цвет
        // теперь задаёт ярус, а насколько ярусы расходятся — дело рендера (см. MountainTierRamp).

        /// <summary>
        /// Суша ли точка (решение ДМ 2026-08-13: горы идут исключительно по суше). null — ограничения
        /// нет; так работает стенд, где никакой карты вокруг не существует.
        ///
        /// Спрашивается ровно в одном месте — при растеризации МАСКИ, до поля расстояний. Тогда суше
        /// подчиняется всё, что ниже по течению разом: и оси, и ярусы, и тон, и производный рельеф.
        /// Два других прочтения хуже. Резать сам мазок нельзя: в файле лежат только мазки, и мазок
        /// обязан остаться тем, что провёл ДМ, — иначе слияние пятен и ластик начнут считаться по
        /// подрезанному. Выбрасывать горы, попавшие на воду, — оставляет дыры посреди цепи.
        ///
        /// Спрашивается из фонового потока, поэтому обязана быть чистой функцией по снимку данных,
        /// а не запросом к живой карте.
        /// </summary>
        public Func<System.Numerics.Vector2, bool> IsLand;

        public float LinkLength => Math.Max(1e-4f, Radius * LinkFactor);

        /// <summary>Сжатие подошвы по вертикали — обратное анизотропии.</summary>
        public float Squash => 1f / Math.Max(1f, Anisotropy);

        /// <summary>Шаг выборки силуэта доли. В прототипе это «каждые 3 px», то есть R/15.</summary>
        public float SampleStep => Math.Max(1e-4f, Radius / 15f);

        /// <summary>Ширина подошвы, ниже которой горы нет.</summary>
        public float MinSpan => Radius * 0.1f;

        /// <summary>Толщина слоя массы — тот же слой 2R, которым отбираются кольца (§4).</summary>
        public float TierBand => Math.Max(1e-4f, 2f * Radius);

        /// <summary>Выборка кривой подъёма под нынешнюю остроту. Строится по одной на пересчёт.</summary>
        public LiftSamples Profile() => new LiftSamples(Sharp, MoundBuilder.ProfileSamples);
    }

    /// <summary>
    /// mulberry32 — тот же генератор, что в прототипе, до последнего бита. Не «какой-нибудь
    /// случайный»: от него зависит, совпадёт ли посчитанное у ДМ с посчитанным на стенде, и не
    /// перетасуется ли уже нарисованный хребет между запусками.
    /// </summary>
    public sealed class Mulberry32
    {
        uint state;

        public Mulberry32(uint seed) { state = seed; }

        public float Next()
        {
            unchecked
            {
                state += 0x6D2B79F5u;
                uint t = state;
                t = (t ^ (t >> 15)) * (t | 1u);
                t ^= t + (t ^ (t >> 7)) * (t | 61u);
                return (t ^ (t >> 14)) / 4294967296f;
            }
        }
    }
}
