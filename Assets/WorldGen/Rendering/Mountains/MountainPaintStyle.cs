using UnityEngine;
using WorldGen.Generation.Mountains;
using Vec2 = System.Numerics.Vector2;

namespace WorldGen.Rendering.Mountains
{
    /// <summary>
    /// Чем красить горы — манера «тушь» (§13 спеки).
    ///
    /// ЗДЕСЬ НЕТ НИ ОДНОГО ЧИСЛА ВИДА. Все они постоянные и живут в MountainInk: жирность линии,
    /// сход, крошка, порог тени, свет. Так решено 15 августа 2026 — пока каждое из них было полем
    /// компонента, вид гор зависел не от того, что выбрано в превью, а от того, что случайно
    /// оказалось записано в сцене, и дважды подряд картинка расходилась ровно так.
    ///
    /// Осталось только то, что и правда меняется от карты к карте: краска, признак суши, высота слоя
    /// и сколько слоёв массы различать.
    ///
    /// Объём держит ЛИНИЯ, а не цвет. Тело карту не красит СОВСЕМ: оно кладётся прозрачным и только
    /// пишет глубину, чтобы линия дальней горы отсекалась телом ближней. Поэтому сквозь гору видна
    /// ровно та карта, что нарисована, — со сглаживанием, зерном и виньеткой, и никакого шва по краю
    /// быть не может в принципе.
    /// </summary>
    public struct MountainPaintStyle
    {
        /// <summary>Краска туши. Единственная краска слоя: тело карту не красит вовсе.
        ///
        /// Кладётся сюда УЖЕ ПЕРЕВЕДЁННОЙ в линейное пространство (см. ForVertex): проект собран в
        /// Linear, а краску вершины шейдер отдаёт как есть, без перевода.</summary>
        public Color32 Ink;

        /// <summary>Светлый конец шкалы заливки — горный тон палитры карты (MtnL), как он записан в
        /// палитре, БЕЗ перевода в линейное пространство: смешивать надо в том же пространстве, в
        /// каком краски выбирали глазами, а переводить — уже смесь (см. Fill).</summary>
        public Color32 FillLight;

        /// <summary>Тёмный конец шкалы заливки — теневой горный тон палитры (MtnS).</summary>
        public Color32 FillDark;

        /// <summary>Линейное ли пространство у проекта. Спрошено на ГЛАВНОМ потоке при сборке стиля:
        /// сама раскладка идёт в фоне, а QualitySettings — живой движок. Забыть про перевод значит
        /// получить заливку светлее задуманной ровно так же, как однажды вышло с тушью.</summary>
        public bool LinearVertex;

        /// <summary>Суша ли под точкой. null — не спрашивать (стенд, шип). Задаётся тем же снимком,
        /// каким маска обрезается по суше, — иначе рисунок и его обрезка разъедутся.</summary>
        public System.Func<Vec2, bool> OnLand;

        /// <summary>Сколько слоёв массы различаем. Не число вида: от него зависит и геометрия
        /// (по слоям раздаётся высота), поэтому оно живёт в настройках счёта.</summary>
        public int TierCount;

        /// <summary>Высота слоя над плоскостью карты.</summary>
        public float LayerY;

        /// <summary>Густота туши для слоя массы: множит и толщину линии, и плотность крошки.</summary>
        public float Density(int tier) => MountainInk.Density(tier, TierCount);

        /// <summary>
        /// Краска тела по тону: 0 — светлый конец шкалы, 1 — тёмный. Тон считает чистый слой
        /// (MountainFill), здесь остаётся смешать две краски палитры и перевести смесь в то
        /// пространство, в каком её ждёт шейдер.
        ///
        /// Зовётся ИЗ ФОНА, поэтому про активное пространство не спрашивает — оно снято заранее в
        /// LinearVertex. Стоит трёх Pow, и звать её на каждую вершину было бы дорого: тон постоянен
        /// внутри яруса, и раскладка отдаёт вершины ярусами подряд (см. MountainTriangulation).
        /// </summary>
        public Color32 Fill(float tone) => ToVertex(new Color32(
            MountainFill.Blend(FillLight.r, FillDark.r, tone),
            MountainFill.Blend(FillLight.g, FillDark.g, tone),
            MountainFill.Blend(FillLight.b, FillDark.b, tone), 255), LinearVertex);

        /// <summary>
        /// Краска туши — ПОЧТИ ЧЁРНАЯ, и от палитры карты она не зависит.
        ///
        /// Первая редакция брала теневой горный тон и притемняла его втрое. На тёплых палитрах это
        /// давало правдоподобную сепию, а на снежной — бледно-серую линию: тон там сам по себе
        /// светлый, и треть от светлого остаётся светлой. ДМ увидел горы, обведённые почти
        /// невидимой линией. Тушь — это тушь: у неё своя чернота, а не производная от карты.
        ///
        /// Непрозрачность ПОЛНАЯ, и это тоже правило манеры, а не мелочь. Полупрозрачная тушь
        /// смешивается с картой в мутный тон, а на стыке двух наложенных мазков темнеет вдвое —
        /// именно так контур и читался «полупрозрачным и грязным». Непрозрачная краска ещё и
        /// развязывает руки раскладке: перекрывающиеся куски ленты рисуют одну сплошную линию.
        /// </summary>
        public static Color32 DefaultInk => new Color32(26, 22, 18, 255);

        /// <summary>
        /// Краска, как её надо положить в ВЕРШИНУ меша.
        ///
        /// Проект собран в линейном пространстве (ProjectSettings, m_ActiveColorSpace: 1). Текстуры
        /// и Material.SetColor Unity переводит сама, а краску вершины — НЕТ: шейдер получает байт
        /// как есть и отдаёт его как линейную величину. Поэтому почти чёрный 26 из 255 выходил на
        /// экран как 90 из 255 — мутный серо-коричневый. ДМ увидел это как «контур почему-то
        /// полупрозрачный»; прозрачности там не было вовсе, был не тот перевод.
        ///
        /// Переводится ТОЛЬКО цвет. Непрозрачность линейна сама по себе, и переводить её — значит
        /// молча высветлить всю тушь второй раз.
        ///
        /// Спрашивать активное пространство надо на ГЛАВНОМ потоке: меш собирается в фоне, а
        /// QualitySettings — живой движок. Поэтому перевод делается здесь, при сборке стиля, а не
        /// при раскладке, которую зовут из фона.
        /// </summary>
        public static Color32 ForVertex(Color32 c) => ToVertex(c, IsLinear);

        /// <summary>Линейное ли сейчас пространство. Спрашивать это МОЖНО ТОЛЬКО с главного потока —
        /// потому оно и снимается в LinearVertex один раз на сборку стиля.</summary>
        public static bool IsLinear => QualitySettings.activeColorSpace == ColorSpace.Linear;

        /// <summary>Тот же перевод, но пространство сказано снаружи: годится для фона.</summary>
        public static Color32 ToVertex(Color32 c, bool linear)
        {
            if (!linear) return c;
            Color lin = ((Color)c).linear;
            return new Color32((byte)(lin.r * 255f + 0.5f), (byte)(lin.g * 255f + 0.5f),
                               (byte)(lin.b * 255f + 0.5f), c.a);
        }
    }
}
