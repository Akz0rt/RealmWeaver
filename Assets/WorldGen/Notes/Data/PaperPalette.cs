namespace WorldGen.Notes.Data
{
    /// <summary>Тон листа: цвет ПЛЮС прозрачность, в отличие от PaletteColor. Прозрачность здесь
    /// не отдельная галка, а свойство тона — тогда в файле лежит одно число, а правило «ластик
    /// возвращает лист к его цвету» остаётся одним правилом без частного случая.</summary>
    public readonly struct PaperTone
    {
        public readonly byte R, G, B, A;
        public PaperTone(byte r, byte g, byte b, byte a) { R = r; G = g; B = b; A = a; }
    }

    /// <summary>Короткий список тонов бумаги.
    ///
    /// ПАЛИТРА ЧЕРНИЛ (NotesPalette) ДЛЯ ЛИСТА НЕ ГОДИТСЯ и не переиспользуется: все девять её
    /// цветов средние и тёмные, они сделаны для рамки и карандаша. Белого в ней нет вовсе — то есть
    /// сегодняшний вид рисунка ею невыразим, — а чернильный цвет на чернильном листе дал бы
    /// невидимую линию.
    ///
    /// СПИСОК ДОПОЛНЯЕТСЯ ТОЛЬКО С КОНЦА, по той же причине, что и NotesPalette: в файле проекта
    /// лежит ИНДЕКС, и перестановка перекрасила бы уже сохранённые чужие проекты.</summary>
    public static class PaperPalette
    {
        static readonly PaperTone[] Tones =
        {
            new PaperTone(255, 255, 255, 255),  // 0 белый — значение по умолчанию
            new PaperTone(242, 232, 208, 255),  // 1 кремовый пергамент
            new PaperTone(226, 226, 230, 255),  // 2 светло-серый
            new PaperTone( 46,  46,  52, 255),  // 3 тёмный грифельный
            // 4 ПРОЗРАЧНЫЙ. RGB белый, а НЕ чёрный, и это не вкусовщина: текстура рисунка
            // фильтруется билинейно и всегда растянута, поэтому цвет смешивается и с полностью
            // прозрачными пикселями. При 0,0,0,0 вокруг каждой линии появилась бы тёмная кайма.
            // Сегодняшний ластик уже пишет 255,255,255,0 — ровно эта мера предосторожности.
            new PaperTone(255, 255, 255, 0),
        };

        public static readonly string[] Names =
        { "Белый", "Пергамент", "Светло-серый", "Грифельный", "Прозрачный" };

        /// <summary>Ноль, потому что отсутствующий в файле ключ читается как 0 — и обязан
        /// воспроизводить сегодняшний вид. Это то же соглашение, что Medium = 0 у кегля и толщины
        /// кисти в формате 15.</summary>
        public const int WhiteIndex = 0;
        public const int TransparentIndex = 4;
        public static int Count => Tones.Length;

        /// <summary>Индекс вне списка — файл из будущей версии или битые данные, а не повод
        /// падать: возвращается белый.</summary>
        public static PaperTone At(int index)
            => index < 0 || index >= Tones.Length ? Tones[WhiteIndex] : Tones[index];
    }
}
