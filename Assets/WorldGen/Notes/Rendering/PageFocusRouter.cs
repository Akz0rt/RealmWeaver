using UnityEngine.EventSystems;
using WorldGen.Workspace.Rendering;

namespace WorldGen.Notes.Rendering
{
    /// <summary>
    /// Задача 5 арки «две страницы рядом»: ОДИН вопрос — «какому виду страницы сейчас принадлежат
    /// клавиши» — и одно место, где на него отвечают. С задачи 4 вид страницы строится ПО ЭКЗЕМПЛЯРУ НА
    /// ПАНЕЛЬ (PageSurfaceHost), так что обработчик клавиш, попап «@» и Ctrl+F больше не могут быть
    /// проведены к «тому самому единственному виду» — до этой задачи они были жёстко привязаны к панели 0,
    /// и печать во второй панели проваливалась в голые TMP-поля: текст правился, а Enter/Tab/Backspace/
    /// отмена не доходили до списка блоков.
    ///
    /// ОПРОС, А НЕ ПОЛЕ «ТЕКУЩИЙ ВИД», и это главное решение этого класса. Поле пришлось бы обновлять на
    /// КАЖДОМ пути смены фокуса — клик по вкладке, клик в содержимое другой панели, продвижение панели при
    /// закрытии вкладки, восстановление раскладки из настроек, перетаскивание вкладки в другую панель,
    /// «↗» разворачивающая доску в соседнюю панель — и одного забытого пути хватает, чтобы поле
    /// разошлось с действительностью НАВСЕГДА. Промах при этом выглядит не как «ничего не работает», а как
    /// «отмена прилетела в чужую панель», то есть как порча данных на глазах у ДМ. Опрос каретки такого
    /// состояния не имеет вовсе: он читает то, что есть ПРЯМО СЕЙЧАС, и потому самовосстанавливается —
    /// любой путь, который мы не предусмотрели, уже учтён, потому что каретка после него стоит там, где
    /// стоит.
    ///
    /// ЖИВЁТ РОВНО СТОЛЬКО, СКОЛЬКО ХОСТ, КОТОРЫЙ ОБОРАЧИВАЕТ. Обычный C#-класс (не MonoBehaviour):
    /// WorkspaceBuilder.Awake создаёт его рядом с PageSurfaceHost и раздаёт ссылку на него, а следующая
    /// пересборка оболочки создаёт и хост, и маршрутизатор заново — так что указать на снесённый
    /// PageSurfaceHost он не может в принципе. Это тот же довод, которым SurfaceRegistry обходится без
    /// «восстановления после перезагрузки домена».
    ///
    /// СЛОЙ. Это первая ссылка из WorldGen.Notes.Rendering в WorldGen.Workspace.Rendering (до сих пор
    /// notes-слой знал только WorldGen.Workspace.Data — см. MentionSuggest, DocumentPageView). Сделано
    /// сознательно и по заданию: вопрос «какая панель активна» ОТНОСИТСЯ к оболочке, и заводить ради него
    /// три делегата-переходника значило бы прятать ту же самую зависимость, а не убирать её. Чистая
    /// половина notes-слоя (WorldGen.Notes.Data) этим не задета — офлайн-харнесс компилирует только её.
    /// </summary>
    public class PageFocusRouter
    {
        readonly PageSurfaceHost host;
        readonly WorkspaceController controller;

        public PageFocusRouter(PageSurfaceHost host, WorkspaceController controller)
        {
            this.host = host;
            this.controller = controller;
        }

        /// <summary>Вид, которому принадлежит поле с кареткой; при отсутствии каретки — вид АКТИВНОЙ
        /// панели; null, если такого вида нет вовсе.
        ///
        /// ВТОРАЯ СТУПЕНЬ ТРЕБУЕТ SurfaceVisible, и это не перестраховка. PageSurfaceHost.Hide СОЗНАТЕЛЬНО
        /// не отвязывает страницу от вида (иначе каждая синхронизация поверхностей стирала бы историю
        /// отмены), так что вид остаётся привязан к странице ещё долго после того, как перестал её
        /// показывать: `Page != null` означает «когда-то показывал», и только `SurfaceVisible` означает
        /// «показывает сейчас». Без этой проверки Ctrl+Z в панели, где открыта карта или подземелье, тихо
        /// откатывал бы правку в НЕВИДИМОЙ странице этой же панели.
        ///
        /// NULL — ЗАКОННЫЙ ОТВЕТ, а не дыра. Если активная панель показывает не страницу, у клавиш
        /// страницы владельца нет: ноль владельцев здесь честнее, чем «отдадим соседней панели» —
        /// последнее вернуло бы ровно ту отмену-не-в-той-панели, ради которой задача и делается. Ровно ДВА
        /// владельца невозможны структурно: DocKeyboardController в проекте один (NotesRootBuilder
        /// AddComponent-ит его единожды), и он спрашивает этот метод один раз за кадр.
        ///
        /// РАЗВЁРНУТАЯ ДОСКА — ЕДИНСТВЕННЫЙ СЛУЧАЙ, ГДЕ NULL СТОИТ ЧЕГО-ТО ЗАМЕТНОГО, и он записан здесь,
        /// а не молчком. Доска (Р4) — это БЛОК страницы, своей истории отмены у неё нет: мутации доски
        /// кладёт в историю CanvasSurfaceHost.BeforeMutation, и кладёт их в тот вид, который СЕЙЧАС
        /// ПОКАЗЫВАЕТ страницу-владельца (CanvasSurfaceHost.ViewShowing, тоже по SurfaceVisible). Пока
        /// страница открыта в соседней панели, всё сходится: ДМ щёлкает в неё, она становится активной,
        /// Ctrl+Z идёт ровно в тот вид, куда доска писала историю. Но если ДМ щёлкнул в САМУ ДОСКУ (её
        /// панель стала активной, а вид страницы в ней скрыт) — этот метод вернёт null, и Ctrl+Z не
        /// сделает ничего. До задачи 5 в этом месте отмена уходила в жёстко привязанный вид панели 0, то
        /// есть в НЕВИДИМУЮ страницу и в стек, куда доска как раз ничего и не писала, — «сработало» она
        /// только в той единственной раскладке, где вид панели 0 случайно оказывался и адресатом истории.
        /// Правильный ответ («клавиши доски принадлежат виду, показывающему её страницу») требует, чтобы
        /// этот класс знал про поверхность-доску, а её панельная модель ещё не готова — временный охранник
        /// в WorkspaceController.SyncSurfaces для Canvas снимает задача 6. Чинить это здесь раньше значит
        /// строить вторую половину моста навстречу той, которую ещё не начали.</summary>
        public DocumentPageView ActiveView()
        {
            if (host == null) return null;

            var underCaret = ViewUnderCaret();
            if (underCaret != null) return underCaret;

            var layout = controller != null ? controller.Layout : null;
            if (layout == null) return null;

            var focused = host.ViewFor(layout.FocusedPane);
            return focused != null && focused.SurfaceVisible ? focused : null;
        }

        /// <summary>Вид, в чьей иерархии лежит объект, выбранный EventSystem'ом, — то есть тот, в чьём поле
        /// физически стоит каретка. `GetComponentInParent` — это и есть подъём по `transform.parent` до
        /// первого попавшегося DocumentPageView; писать цикл вручную значило бы повторить его же, только с
        /// собственной опечаткой.
        ///
        /// SurfaceVisible ТРЕБУЕТСЯ И ЗДЕСЬ, хотя выглядит недостижимым. Первая редакция этого метода
        /// обходилась без проверки и объясняла это тем, что «выключенный объект не бывает
        /// currentSelectedGameObject». Ревью проверило по исходникам пакетов, а не по памяти, и это
        /// НЕПРАВДА: `EventSystem` нигде не сверяет своё выделение с `activeInHierarchy`,
        /// `TMP_InputField.OnDisable → DeactivateInputField` выделения EventSystem не трогает, а
        /// единственное место, которое его снимает (`InputSystemUIInputModule`), делает это на нажатии
        /// указателя. То есть гашение `root` само по себе выделение НЕ снимает — сегодня ступень 1
        /// защищена лишь тем, что каждый путь, скрывающий вид, проходит через клик или уничтожает
        /// выделенный объект. Это свойство ЧУЖИХ компонентов, а не инвариант этого класса.
        ///
        /// Цена ошибки при этом несимметрична: вид сидит на обёртке «PageSurface», которая остаётся
        /// ВКЛЮЧЁННОЙ всегда (гасится только её ребёнок `root`), так что `GetComponentInParent` спокойно
        /// вернул бы СКРЫТЫЙ вид — и Ctrl+Z уехал бы в невидимую страницу, то есть ровно в тот дефект,
        /// ради которого написан весь класс. Одна строка проверки не зависит ни от какого чужого кода и
        /// честный путь сломать не может: у видимого вида она всегда истинна.</summary>
        DocumentPageView ViewUnderCaret()
        {
            var events = EventSystem.current;
            var selected = events != null ? events.currentSelectedGameObject : null;
            if (selected == null) return null;

            var view = selected.GetComponentInParent<DocumentPageView>();
            return view != null && view.SurfaceVisible ? view : null;
        }
    }
}
