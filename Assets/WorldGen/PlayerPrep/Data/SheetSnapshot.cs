namespace WorldGen.PlayerPrep.Data
{
    /// <summary>«Изменилось ли что-нибудь с последней записи» — снимком, а не флажками.
    ///
    /// СНИМОК, А НЕ ПОМЕТКИ РУКАМИ, и это главное решение этого файла. Правку листа сегодня делают
    /// мастер (восемь шагов, десятки полей), сам лист (имя, портрет, предыстория, хиты) и завтра —
    /// то, чего ещё нет. Помечай каждое место правки вручную, и цена одной забытой строчки — молча
    /// потерянная работа игрока: диалог при выходе просто не появится. Снимок ловит ВСЁ, потому что
    /// сравнивает не намерения, а результат.
    ///
    /// Снимается ТЕМ ЖЕ способом, каким файл пишется на диск (CharacterSerializer.ToJson — ровно то,
    /// что зовёт SheetFileService.Save). Это не совпадение, а требование: сравнение обязано считать
    /// изменением ровно то, что запись сохранит, и ничего сверх. Возьми снимок каким-нибудь своим
    /// обходом полей — и разойтись с записью он смог бы в обе стороны сразу: пропущенное поле даёт
    /// молчаливую потерю, лишнее (не пишущееся в файл) — вопрос «сохранить?» там, где сохранять
    /// нечего.
    ///
    /// ПОБОЧНОЕ ДЕЙСТВИЕ У ToJson ЕСТЬ: он проставляет file.FormatVersion = CurrentFormatVersion.
    /// Оно безобидно (то же самое сделает и запись, и повторный вызов ничего не меняет), но знать про
    /// него надо: Of — не совсем чистая функция, а «чистая по результату».</summary>
    public static class SheetSnapshot
    {
        /// <summary>Снимок сохранённого состояния. null — «ничего не открыто»: на экране списка
        /// сравнивать не с чем и спрашивать не о чем.
        ///
        /// ⚠ ЗАПРОС, КОТОРЫЙ ПИШЕТ. ToJson проставляет file.FormatVersion = CurrentFormatVersion, а
        /// зовёт его в том числе HasUnsavedChanges — то есть «изменилось ли что-нибудь» МЕНЯЕТ поле
        /// листа. Сегодня это тождество и потому безвредно: CurrentFormatVersion равен единице, поле
        /// по умолчанию единица, а ложного «изменено» не выходит, потому что RememberSaved снимает
        /// снимок ТЕМ ЖЕ вызовом — обе стороны сравнения получают одну и ту же запись.
        ///
        /// Перестанет быть безвредным ровно тогда, когда формат вырастет и FromJson начнёт МИГРИРОВАТЬ
        /// по FormatVersion: прочитанный лист версии 1 после первого же Of() будет числиться версией 2,
        /// хотя его никто не мигрировал. Понадобится это менять — берите снимок не ToJson, а его
        /// частью, которая ничего не проставляет.</summary>
        public static string Of(CharacterFile file) =>
            file == null ? null : CharacterSerializer.ToJson(file);

        /// <summary>Разошёлся ли лист со своим снимком.
        ///
        /// Снимок null при непустом листе — ИЗМЕНЕНИЕ, а не «нечего сравнивать»: так выглядит лист,
        /// который ни разу не записывали, и промолчать про него значило бы потерять его целиком.</summary>
        public static bool Differs(string snapshot, CharacterFile file) =>
            !string.Equals(snapshot, Of(file), System.StringComparison.Ordinal);
    }
}
