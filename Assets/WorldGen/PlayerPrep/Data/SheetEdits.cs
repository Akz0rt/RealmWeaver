using System.Globalization;

namespace WorldGen.PlayerPrep.Data
{
    /// <summary>Правила мелких правок, которые игрок делает прямо на листе, без захода в мастер.
    /// Живут здесь, а не в слое рисования, по общему правилу арки: правило, которое никто не
    /// проверяет, расходится с тем, что показано, при первой же правке соседнего кода.</summary>
    public static class SheetEdits
    {
        /// <summary>Меньше единицы максимум хитов не бывает. То же число, что и в SheetMath у
        /// посчитанного максимума (Math.Max(1, …)): персонаж с нулём хитов не «почти мёртв», он
        /// невозможен.</summary>
        public const int MinMaxHp = 1;

        /// <summary>Что вписали в поле «свой максимум хитов» → что положить в CharacterFile.MaxHpOverride.
        ///
        /// ПУСТО ЗНАЧИТ null, то есть «считай среднее из справочника», и это единственный способ
        /// ОТКАЗАТЬСЯ от вписанного числа набором с клавиатуры: стереть поле. Верни здесь ноль вместо
        /// null — и стёртое поле означало бы «максимум хитов ноль», то есть вписанное число нельзя
        /// было бы убрать вовсе, а лист показал бы мёртвого персонажа.
        ///
        /// Нечисло тоже даёт null. Поле на листе принимает только цифры, так что взяться такому
        /// неоткуда, — но «неоткуда» здесь означает «пока»: разбор, который на мусоре возвращает
        /// число, однажды тихо запишет это число в чужой лист.
        ///
        /// Разбор ИНВАРИАНТНЫЙ, не по языку системы: в файл ложится число, а не текст, и «42»,
        /// набранное на машине с другим разделителем, обязано означать то же самое.</summary>
        public static int? ParseMaxHpOverride(string text)
        {
            if (string.IsNullOrWhiteSpace(text)) return null;
            if (!int.TryParse(text.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out int value))
                return null;
            return value < MinMaxHp ? MinMaxHp : value;
        }
    }
}
